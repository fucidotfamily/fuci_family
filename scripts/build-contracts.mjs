// Compiles contracts/FuciAgentFactory.sol with solc-js and writes lib/factoryArtifact.ts (ABI + bytecode).
// Run: npm run contracts:build
import { readFileSync, writeFileSync } from "node:fs";
import solc from "solc";

const source = readFileSync(new URL("../contracts/FuciAgentFactory.sol", import.meta.url), "utf8");
const input = {
  language: "Solidity",
  sources: { "FuciAgentFactory.sol": { content: source } },
  settings: { optimizer: { enabled: true, runs: 200 }, evmVersion: "cancun", outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } } },
};
const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (out.errors ?? []).filter((e) => e.severity === "error");
for (const e of out.errors ?? []) console.error(e.formattedMessage);
if (errors.length) process.exit(1);
const c = out.contracts["FuciAgentFactory.sol"].FuciAgentFactory;
writeFileSync(
  new URL("../lib/factoryArtifact.ts", import.meta.url),
  `// Generated by scripts/build-contracts.mjs from contracts/FuciAgentFactory.sol (solc ${solc.version()}, optimizer 200, cancun). Do not edit.\n` +
    `export const FACTORY_ABI = ${JSON.stringify(c.abi, null, 2)} as const;\n\n` +
    `export const FACTORY_BYTECODE = "0x${c.evm.bytecode.object}" as const;\n`,
);
console.log("compiled with", solc.version(), "bytecode bytes:", c.evm.bytecode.object.length / 2);
