// Compiles the contracts in contracts/ with solc-js and writes their ABI + bytecode to lib/*Artifact.ts.
// Run: npm run contracts:build   (tests: forge test --root contracts, see contracts/README.md)
import { readFileSync, writeFileSync } from "node:fs";
import solc from "solc";

const CONTRACTS = [
  { file: "FuciAgentFactory.sol", name: "FuciAgentFactory", out: "factoryArtifact.ts", prefix: "FACTORY" },
  { file: "FuciEscrow.sol", name: "FuciEscrow", out: "escrowArtifact.ts", prefix: "ESCROW" },
];

for (const c of CONTRACTS) {
  const source = readFileSync(new URL(`../contracts/${c.file}`, import.meta.url), "utf8");
  const input = {
    language: "Solidity",
    sources: { [c.file]: { content: source } },
    settings: { optimizer: { enabled: true, runs: 200 }, evmVersion: "cancun", outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } } },
  };
  const out = JSON.parse(solc.compile(JSON.stringify(input)));
  const errors = (out.errors ?? []).filter((e) => e.severity === "error");
  for (const e of out.errors ?? []) console.error(e.formattedMessage);
  if (errors.length) process.exit(1);
  const art = out.contracts[c.file][c.name];
  writeFileSync(
    new URL(`../lib/${c.out}`, import.meta.url),
    `// Generated by scripts/build-contracts.mjs from contracts/${c.file} (solc ${solc.version()}, optimizer 200, cancun). Do not edit.\n` +
      `export const ${c.prefix}_ABI = ${JSON.stringify(art.abi, null, 2)} as const;\n\n` +
      `export const ${c.prefix}_BYTECODE = "0x${art.evm.bytecode.object}" as const;\n`,
  );
  console.log(c.name, "compiled with", solc.version(), "bytecode bytes:", art.evm.bytecode.object.length / 2);
}
